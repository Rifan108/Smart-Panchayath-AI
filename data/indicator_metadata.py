    """Retrieve metadata dict for a given indicator id with sensible fallback."""
    if indicator_id in INDICATOR_METADATA:
        return INDICATOR_METADATA[indicator_id]
    
    clean_name = indicator_id.replace("_", " ").title()
    return {
        "id": indicator_id,
        "name": clean_name,
        "sector": "General Governance",
        "definition": f"Standardized developmental metric measuring {clean_name.lower()} across participating wards.",
        "unit": "ratio / score",
        "direction": "Normalized Index (0.00 - 1.00)",
        "source": "Verified Government Statistics",
        "period": "2023-2024",
    }

